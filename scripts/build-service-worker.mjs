import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const dist = join(root, 'dist')

async function filesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await filesUnder(path))
    else if (entry.isFile() && entry.name !== 'sw.js') files.push(path)
  }
  return files
}

const files = await filesUnder(dist)
const paths = files
  .map((path) => relative(dist, path).split(sep).join('/'))
  .sort((left, right) => left.localeCompare(right, 'en-US'))
const versionHash = createHash('sha256')
versionHash.update(await readFile(fileURLToPath(import.meta.url)))
versionHash.update('\0')
for (const path of files.toSorted((left, right) => left.localeCompare(right, 'en-US'))) {
  versionHash.update(relative(dist, path).split(sep).join('/'))
  versionHash.update('\0')
  versionHash.update(await readFile(path))
  versionHash.update('\0')
}
const version = versionHash.digest('hex').slice(0, 16)

const serviceWorker = `/* Generated by scripts/build-service-worker.mjs */
const CACHE_NAME = 'bookrefinery-${version}'
const PRECACHE_PATHS = ${JSON.stringify(paths)}
const rootUrl = new URL('./', self.location.href)
const precacheUrls = PRECACHE_PATHS.map((path) => new URL(path, rootUrl).toString())

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(precacheUrls))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names
        .filter((name) => name.startsWith('bookrefinery-') && name !== CACHE_NAME)
        .map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return
  const requestUrl = new URL(event.request.url)
  if (requestUrl.origin !== self.location.origin) return
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached
      return fetch(event.request).then((response) => {
        if (!response || response.status !== 200) return response
        const copy = response.clone()
        void caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy))
        return response
      }).catch(() => {
        if (event.request.mode === 'navigate') {
          return caches.match(new URL('index.html', rootUrl).toString())
        }
        throw new Error('Offline asset is not available in the application cache.')
      })
    }),
  )
})
`

await writeFile(join(dist, 'sw.js'), serviceWorker, 'utf8')
console.log(`Generated offline service worker for ${paths.length} assets (${version}).`)
